#!/usr/bin/env python3
"""
data/mentees.csv  ->  _includes/mentees_map.en.md and _includes/mentees_map.fr.md

Interactive map of where former mentees work now: a round photo at each
workplace, linked by an arc to Louvain-la-Neuve. Edit the CSV (Excel, R, any
text editor) and rebuild. Columns:
  name, photo (file in assets/img), position_en, position_fr, place, lat, lon,
  dx, dy (pixel shift of the photo when two people share a place; the line
  still ends at the true location), url (optional personal website)
"""
import csv
import html
import json
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOME = {"lat": 50.66662, "lon": 4.61937, "label": "UCLouvain, Louvain-la-Neuve"}

TEXT = {
    "en": {"prefix": "", "aria": "Map of where former mentees work now",
           "web": "Website", "home": "Our lab — UCLouvain, Louvain-la-Neuve",
           "noscript": "The interactive map needs JavaScript; current positions are listed in the cards above."},
    "fr": {"prefix": "../", "aria": "Carte des lieux de travail actuels des anciens mentorés",
           "web": "Site web", "home": "Notre labo — UCLouvain, Louvain-la-Neuve",
           "noscript": "La carte interactive nécessite JavaScript ; les postes actuels figurent dans les fiches ci-dessus."},
}


def main():
    with open(os.path.join(HERE, "data", "mentees.csv"), encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["name"].strip()]
    for lang, t in TEXT.items():
        pts = []
        for r in rows:
            pts.append({
                "name": r["name"], "photo": t["prefix"] + "assets/img/" + r["photo"],
                "pos": r["position_" + lang], "place": r["place"],
                "lat": float(r["lat"]), "lon": float(r["lon"]),
                "dx": int(r["dx"] or 0), "dy": int(r["dy"] or 0), "url": r["url"].strip(),
            })
        data = json.dumps({"home": HOME, "pts": pts, "web": t["web"], "homeLabel": t["home"]}, ensure_ascii=False)
        p = t["prefix"]
        out = f"""<!-- GENERATED by tools/build_mentees_map.py from data/mentees.csv — do not edit -->

```{{=html}}
<link rel="stylesheet" href="{p}assets/vendor/leaflet/leaflet.css">
<div id="mentees-map" class="mentees-map" role="region" aria-label="{html.escape(t['aria'])}"></div>
<noscript><p>{html.escape(t['noscript'])}</p></noscript>
<script src="{p}assets/vendor/leaflet/leaflet.js"></script>
<script>
(function () {{
  var D = {data};
  var map = L.map("mentees-map", {{scrollWheelZoom: false, worldCopyJump: true}});
  L.tileLayer("https://{{s}}.basemaps.cartocdn.com/light_all/{{z}}/{{x}}/{{y}}{{r}}.png", {{
    maxZoom: 18, subdomains: "abcd",
    attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> &copy; <a href="https://carto.com/attributions">CARTO</a>'
  }}).addTo(map);
  function esc(s) {{ var d = document.createElement("div"); d.textContent = s; return d.innerHTML; }}
  function arc(a, b) {{
    var mx = (a[0] + b[0]) / 2, my = (a[1] + b[1]) / 2, dx = b[0] - a[0], dy = b[1] - a[1];
    var c = [mx - dy * 0.2, my + dx * 0.2], out = [];
    for (var i = 0; i <= 32; i++) {{
      var t = i / 32, u = 1 - t;
      out.push([u * u * a[0] + 2 * u * t * c[0] + t * t * b[0], u * u * a[1] + 2 * u * t * c[1] + t * t * b[1]]);
    }}
    return out;
  }}
  var home = [D.home.lat, D.home.lon], bounds = [home];
  D.pts.forEach(function (p) {{
    var ll = [p.lat, p.lon];
    bounds.push(ll);
    L.polyline(arc(home, ll), {{color: "#e0700f", weight: 2, opacity: .8}}).addTo(map);
  }});
  L.circleMarker(home, {{radius: 7, color: "#10195c", weight: 2, fillColor: "#1b2a8a", fillOpacity: 1}})
    .addTo(map).bindTooltip(esc(D.homeLabel));
  D.pts.forEach(function (p) {{
    var s = 46;
    var icon = L.divIcon({{
      className: "mentee-pin", iconSize: [s, s], iconAnchor: [s / 2 - p.dx, s / 2 - p.dy],
      html: '<img src="' + p.photo + '" alt="' + esc(p.name) + '">'
    }});
    var pop = "<strong>" + esc(p.name) + "</strong><br>" + esc(p.pos) + "<br><span class=\\"mentee-place\\">" + esc(p.place) + "</span>";
    if (p.url) pop += '<br><a href="' + p.url + '" target="_blank" rel="noopener">' + esc(D.web) + "</a>";
    L.marker([p.lat, p.lon], {{icon: icon, title: p.name, alt: p.name, keyboard: true}}).addTo(map).bindPopup(pop);
  }});
  map.fitBounds(bounds, {{padding: [40, 40]}});
}})();
</script>
```
"""
        with open(os.path.join(HERE, "_includes", f"mentees_map.{lang}.md"), "w", encoding="utf-8") as f:
            f.write(out)
    print(f"mentees map: {len(rows)} people")


if __name__ == "__main__":
    main()
