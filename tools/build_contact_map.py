#!/usr/bin/env python3
"""
data/contact_places.csv  ->  _includes/contact_map.en.md and _includes/contact_map.fr.md

Map of how to reach the lab (lab, entrance, parkings, train and bus stations),
rebuilt from the custom Google My Map of the Wix site. Edit the CSV and rebuild.
kind = lab | entrance | parking | train | bus
"""
import csv
import html
import json
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXT = {
    "en": {"prefix": "", "aria": "Map showing the lab, parkings and public transport in Louvain-la-Neuve",
           "layers": {"parking": "Parkings", "transport": "Train and bus"}},
    "fr": {"prefix": "../", "aria": "Carte du labo, des parkings et des transports en commun à Louvain-la-Neuve",
           "layers": {"parking": "Parkings", "transport": "Train et bus"}},
}


def main():
    with open(os.path.join(HERE, "data", "contact_places.csv"), encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["kind"].strip()]
    for lang, t in TEXT.items():
        pts = [{"k": r["kind"], "t": r["label_" + lang], "lat": float(r["lat"]), "lon": float(r["lon"])} for r in rows]
        data = json.dumps({"pts": pts, "layers": t["layers"]}, ensure_ascii=False)
        p = t["prefix"]
        out = f"""<!-- GENERATED by tools/build_contact_map.py from data/contact_places.csv — do not edit -->

```{{=html}}
<link rel="stylesheet" href="{p}assets/vendor/leaflet/leaflet.css">
<div id="contact-map" class="map-embed" role="region" aria-label="{html.escape(t['aria'])}"></div>
<script src="{p}assets/vendor/leaflet/leaflet.js"></script>
<script>
(function () {{
  var D = {data};
  var map = L.map("contact-map", {{scrollWheelZoom: false, zoomSnap: 0.25}});
  L.tileLayer("https://tile.openstreetmap.org/{{z}}/{{x}}/{{y}}.png", {{
    maxZoom: 19, attribution: '&copy; <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors'
  }}).addTo(map);
  var GLYPH = {{lab: "", entrance: "", parking: "P", train: "&#x1F686;&#xFE0E;", bus: "&#x1F68C;&#xFE0E;"}};
  var groups = {{parking: L.layerGroup().addTo(map), transport: L.layerGroup().addTo(map), lab: L.layerGroup().addTo(map)}};
  var all = [];
  D.pts.forEach(function (p) {{
    var ll = [p.lat, p.lon], m;
    if (p.k === "lab") {{
      m = L.marker(ll, {{icon: L.divIcon({{className: "cm-lab", iconSize: [26, 26], iconAnchor: [13, 26], html: "<span></span>"}}), title: p.t, zIndexOffset: 1000}});
      m.bindTooltip(p.t.split(" — ")[0], {{permanent: true, direction: "top", offset: [0, -24], className: "cm-tip"}});
    }} else if (p.k === "entrance") {{
      m = L.circleMarker(ll, {{radius: 6, color: "#fff", weight: 2, fillColor: "#e0700f", fillOpacity: 1}});
    }} else {{
      m = L.marker(ll, {{icon: L.divIcon({{className: "cm-ico cm-" + p.k, iconSize: [24, 24], html: GLYPH[p.k]}}), title: p.t}});
    }}
    m.bindPopup(p.t);
    (p.k === "parking" ? groups.parking : (p.k === "train" || p.k === "bus") ? groups.transport : groups.lab).addLayer(m);
    all.push(ll);
  }});
  var ov = {{}};
  ov[D.layers.parking] = groups.parking;
  ov[D.layers.transport] = groups.transport;
  L.control.layers(null, ov, {{collapsed: false}}).addTo(map);
  map.fitBounds(all, {{padding: [24, 24]}});
}})();
</script>
```
"""
        with open(os.path.join(HERE, "_includes", f"contact_map.{lang}.md"), "w", encoding="utf-8") as f:
            f.write(out)
    print(f"contact map: {len(rows)} places")


if __name__ == "__main__":
    main()
